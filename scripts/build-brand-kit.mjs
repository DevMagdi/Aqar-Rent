/** Minimal ICO writer: ICONDIR + PNG-compressed entries (Vista+ format). */
function buildIco(pngs, sizes) {
  const count = pngs.length;
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(count, 4);
  const entries = Buffer.alloc(16 * count);
  let offset = 6 + 16 * count;
  const blobs = [];
  pngs.forEach((data, i) => {
    const size = sizes[i];
    entries.writeUInt8(size >= 256 ? 0 : size, i * 16 + 0);
    entries.writeUInt8(size >= 256 ? 0 : size, i * 16 + 1);
    entries.writeUInt8(0, i * 16 + 2);
    entries.writeUInt8(0, i * 16 + 3);
    entries.writeUInt16LE(1, i * 16 + 4);
    entries.writeUInt16LE(32, i * 16 + 6);
    entries.writeUInt32LE(data.length, i * 16 + 8);
    entries.writeUInt32LE(offset, i * 16 + 12);
    offset += data.length;
    blobs.push(data);
  });
  return Buffer.concat([header, entries, ...blobs]);
}

