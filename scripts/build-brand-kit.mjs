const DEEP = C["brand-deep"].value;
const GOLD = C.gold.value;
const GOLD_LIGHT = C["gold-light"].value;
const GOLD_DARK = C["gold-dark"].value;
const ON_DARK = C["on-dark"].value;
const WHITE = "#FFFFFF";
const BLACK = "#000000";

const FONT_DISPLAY = TOKENS.font.display.value;
const FONT_SANS = TOKENS.font.sans.value;
const TAGLINE_AR = "إيجارك مباشرة من المالك";
