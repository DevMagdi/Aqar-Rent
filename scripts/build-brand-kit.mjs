function buildAnimated() {
  // SMIL: the hexagon draws itself, then the house appears inside it. No JS,
  // no font, respects prefers-reduced-motion via a CSS media query.
  const draw = (d, delay, color) =>
    `<path d="${d}" fill="none" stroke="${color}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" ` +
    `pathLength="1" stroke-dasharray="1" stroke-dashoffset="1">` +
    `<animate attributeName="stroke-dashoffset" from="1" to="0" dur="0.9s" begin="${delay}s" fill="freeze" calcMode="spline" keySplines="0.22 1 0.36 1" keyTimes="0;1"/>` +
    `</path>`;
  const body =
    `<defs>${gradientDefs("grad")}<style>@media (prefers-reduced-motion: reduce){animate{display:none}path[stroke-dasharray]{stroke-dashoffset:0!important}}</style></defs>` +
    draw(HEX, 0, GOLD) +
    draw(ROOF, 0.55, GOLD_LIGHT) +
    draw(BODY, 0.8, GOLD) +
    `<path d="${KEYHOLE}" fill="${GOLD}" opacity="0"><animate attributeName="opacity" from="0" to="1" dur="0.4s" begin="1.2s" fill="freeze"/></path>`;
  put("01-Logo/Animated/aqar-mark-draw.svg", svg(96, 96, body));
  put(
    "01-Logo/Animated/README.md",
    [
      "# Animated mark",
      "",
      "`aqar-mark-draw.svg` is self-contained SMIL: the hexagon draws, then the house",
      "and keyhole appear. It honours `prefers-reduced-motion` through an inline media",
      "query, so it can be embedded with `<img>` or `<object>` with no JavaScript.",
      "",
      "It is **not** shipped as a Lottie file: Lottie would add a ~500 KB runtime to the",
      "web bundle and a dependency to the app for one 1.6 s stroke animation. The SVG is",
      "1.5 KB and runs natively in every target. (Design spec: “optional lottie” —",
      "declined for bundle budget; see docs/design/visual-identity-report.md.)",
      "",
    ].join("\n"),
  );
}

