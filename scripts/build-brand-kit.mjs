/* ── the mark ──────────────────────────────────────────────────────────────
 * Hexagon: the Mantiq geometry, unchanged — 24,2 43,13 43,35 24,46 5,35 5,13
 * inside a 48-unit viewBox. Inside it, the negative space is a house: a roof
 * curve whose apex leans the way the Arabic «ع» bowl leans, and a keyhole that
 * unifies the stroke weight with the roof. The keyhole is the "rent" idea:
 * one door, one key, no middleman.
 */
const HEX = "M24 2 43 13 43 35 24 46 5 35 5 13Z";
const ROOF = "M10.5 22.6 24 11.6 37.5 22.6";
const BODY = "M15.1 22.4v8.2a2.6 2.6 0 0 0 2.6 2.6h12.6a2.6 2.6 0 0 0 2.6-2.6v-8.2";
const KEYHOLE = "M24 25.4a2.55 2.55 0 0 1 1.65 4.5l.55 2.3h-4.4l.55-2.3A2.55 2.55 0 0 1 24 25.4Z";
const STROKE = 3.1; // one weight for roof + body: 1.75px at 27px render

const gradientDefs = (id, from = GOLD_LIGHT, mid = GOLD, to = GOLD_DARK) =>
  `<linearGradient id="${id}" x1="6" y1="4" x2="42" y2="44" gradientUnits="userSpaceOnUse">` +
  `<stop offset="${STOPS[0]}" stop-color="${from}"/><stop offset="${STOPS[1]}" stop-color="${mid}"/>` +
  `<stop offset="${STOPS[2]}" stop-color="${to}"/></linearGradient>`;

/** Mark as an SVG body: gold hexagon, with the house carved out as negative space. */
function markBody({ fill = "url(#grad)", defs = gradientDefs("grad"), id = "mk", stroke = STROKE } = {}) {
  return (
    defs +
    // The mask subtracts the roof, the body and the keyhole, so the house is
    // whatever is behind the logo — navy on a dark surface, paper on a light one.
    `<mask id="${id}"><rect width="48" height="48" fill="#000"/><path d="${HEX}" fill="#fff"/>` +
    `<g fill="none" stroke="#000" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">` +
    `<path d="${ROOF}"/><path d="${BODY}"/></g>` +
    `<path d="${KEYHOLE}" fill="#000"/></mask>` +
    `<g mask="url(#${id})"><path d="${HEX}" fill="${fill}"/></g>`
  );
}

function svg(width, height, body) {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${round(width)}" height="${round(height)}" ` +
    `viewBox="0 0 ${round(width)} ${round(height)}" fill="none">` +
    `<!-- Generated by scripts/build-brand-kit.mjs from design/tokens.json — do not hand-edit. -->` +
    `<title>Aqar Rent — عقار رينت</title>` +
    body +
    `</svg>\n`
  );
}

const round = (n) => Math.round(n * 100) / 100;

/** Mark only, on a 48-unit canvas with optional rounded navy tile behind it. */
function markSvg({ size = 48, fill = "url(#grad)", radius = 0, stroke = STROKE } = {}) {
  const body =
    (radius ? `<rect width="48" height="48" rx="${radius}" fill="${NAVY}"/>` : "") + markBody({ fill, stroke });
  return svg(size, size, body);
}

/** Outlined wordmark placed on the lockup canvas. */
function outline(key, x, y, height, fill) {
  const o = OUTLINES[key];
  const [vx, vy, , vh] = o.viewBox;
  const s = height / vh;
  return `<path transform="translate(${round(x - vx * s)} ${round(y - vy * s)}) scale(${round(s * 1000) / 1000})" d="${o.path}" fill="${fill}"/>`;
}

const arWidth = (h) => (OUTLINES.ar.width / OUTLINES.ar.height) * h;
const enWidth = (h) => (OUTLINES.en.width / OUTLINES.en.height) * h;
const capsWidth = (h) => (OUTLINES.enCaps.width / OUTLINES.enCaps.height) * h;
const taglineWidth = (h) => (OUTLINES.tagline.width / OUTLINES.tagline.height) * h;
const arTaglineWidth = (h) => (OUTLINES.arTagline.width / OUTLINES.arTagline.height) * h;

/**
 * Horizontal lockup: mark + Arabic wordmark, wide-tracked English caps and the
 * tagline. Clear space is one hex height, so the canvas is padded by the mark
 * height on every side — the SVG can be dropped anywhere without clipping it.
 */
function horizontalSvg({ fill = "url(#grad)", text = NAVY, taglineFill = GOLD_DARK, paper = null } = {}) {
  const markH = 132;
  const arH = 62;
  const capsH = 19;
  const tagH = 11;
  const gap = 28;
  const textW = Math.max(arWidth(arH), capsWidth(capsH), taglineWidth(tagH));
  const contentW = markH + gap + textW;
  const contentH = Math.max(markH, arH + 14 + capsH + 9 + tagH);
  const pad = markH;
  const w = contentW + pad * 2;
  const h = contentH + pad * 2;
  const cy = h / 2;
  const tx = pad + markH + gap;
  const top = cy - contentH / 2;
  return svg(
    w,
    h,
    gradientDefs("grad") +
      (paper ? `<rect width="${round(w)}" height="${round(h)}" fill="${paper}"/>` : "") +
      `<g transform="translate(${round(pad)} ${round(cy - markH / 2)}) scale(${round((markH / 48) * 1000) / 1000})">${markBody({ fill })}</g>` +
      outline("ar", tx, top, arH, text) +
      outline("enCaps", tx, top + arH + 14, capsH, text) +
      outline("tagline", tx, top + arH + 14 + capsH + 9, tagH, taglineFill),
  );
}

/** Stacked lockup: mark above the Arabic wordmark, caps and tagline. */
function stackedSvg({ fill = "url(#grad)", text = NAVY, taglineFill = GOLD_DARK, paper = null } = {}) {
  const markH = 150;
  const arH = 56;
  const capsH = 17;
  const tagH = 10;
  const gap = 28;
  const textW = Math.max(arWidth(arH), capsWidth(capsH), taglineWidth(tagH));
  const contentW = Math.max(markH, textW);
  const contentH = markH + gap + arH + 14 + capsH + 9 + tagH;
  const pad = Math.round(markH * 0.85);
  const w = contentW + pad * 2;
  const h = contentH + pad * 2;
  return svg(
    w,
    h,
    gradientDefs("grad") +
      (paper ? `<rect width="${round(w)}" height="${round(h)}" fill="${paper}"/>` : "") +
      `<g transform="translate(${round((w - markH) / 2)} ${round(pad)}) scale(${round((markH / 48) * 1000) / 1000})">${markBody({ fill })}</g>` +
      outline("ar", (w - arWidth(arH)) / 2, pad + markH + gap, arH, text) +
      outline("enCaps", (w - capsWidth(capsH)) / 2, pad + markH + gap + arH + 14, capsH, text) +
      outline("tagline", (w - taglineWidth(tagH)) / 2, pad + markH + gap + arH + 14 + capsH + 9, tagH, taglineFill),
  );
}

/**
 * Social card: navy field + very faint hex pattern, mark, Arabic wordmark and
 * the tagline. One composition, two layouts (centred square, left-set banner)
 * so every platform shows the same identity at whatever crop it applies.
 */
function socialSvg(w, h, { align = "center" } = {}) {
  const unit = Math.min(w, h);
  const banner = align === "left";
  const markH = Math.round(banner ? unit * 0.42 : unit * 0.17);
  const arH = Math.round(banner ? unit * 0.15 : unit * 0.085);
  const tagH = Math.round(unit * (banner ? 0.032 : 0.022));
  const gapV = Math.round(unit * 0.035);
  const cx = w / 2;
  const cy = h / 2;

  const pattern =
    `<pattern id="hex" width="44" height="44" patternUnits="userSpaceOnUse">` +
    `<path d="M22 3 38 12 38 30 22 39 6 30 6 12Z" fill="none" stroke="${ON_DARK}" stroke-opacity="0.06" stroke-width="1"/></pattern>`;
  // A single soft gold glow behind the mark keeps the navy from going flat.
  const glow =
    `<radialGradient id="glow" cx="0.5" cy="0.5" r="0.5">` +
    `<stop offset="0%" stop-color="${GOLD}" stop-opacity="0.24"/>` +
    `<stop offset="100%" stop-color="${GOLD}" stop-opacity="0"/></radialGradient>`;

  let body;
  if (banner) {
    const blockH = markH;
    const left = Math.round(w * 0.07);
    const textX = left + markH + Math.round(markH * 0.34);
    const textTop = cy - Math.round((arH + gapV + tagH) / 2);
    body =
      `<g transform="translate(${left} ${Math.round(cy - blockH / 2)}) scale(${round((markH / 48) * 1000) / 1000})">${markBody({ fill: "url(#grad)", defs: "" })}</g>` +
      outline("ar", textX, textTop, arH, ON_DARK) +
      outline("tagline", textX, textTop + arH + gapV, tagH, GOLD);
  } else {
    const markTop = cy - Math.round(unit * 0.26);
    body =
      `<g transform="translate(${Math.round(cx - markH / 2)} ${markTop}) scale(${round((markH / 48) * 1000) / 1000})">${markBody({ fill: "url(#grad)", defs: "" })}</g>` +
      outline("ar", cx - arWidth(arH) / 2, markTop + markH + gapV * 1.4, arH, ON_DARK) +
      outline("tagline", cx - taglineWidth(tagH) / 2, markTop + markH + gapV * 1.4 + arH + gapV, tagH, GOLD);
  }

  return svg(
    w,
    h,
    `<defs>${gradientDefs("grad")}${pattern}${glow}</defs>` +
      `<rect width="${w}" height="${h}" fill="${DEEP}"/>` +
      `<rect width="${w}" height="${h}" fill="url(#hex)"/>` +
      `<ellipse cx="${round(cx)}" cy="${round(cy)}" rx="${round(unit * 0.62)}" ry="${round(unit * 0.42)}" fill="url(#glow)"/>` +
      body +
      `<rect x="0" y="${h - 5}" width="${w}" height="5" fill="${GOLD}"/>`,
  );
}

/* ── rasters ─────────────────────────────────────────────────────────────── */
function png(sourceSvg, width) {
  const resvg = new Resvg(sourceSvg, {
    fitTo: { mode: "width", value: Math.round(width) },
    background: "rgba(0,0,0,0)",
    logLevel: "error",
  });
  return resvg.render().asPng();
}

/** iOS/Android need opaque PNGs (alpha is rejected) — composite on navy. */
function opaquePng(sourceSvg, width, background) {
  const resvg = new Resvg(sourceSvg.replace("<title>", `<title>`), {
    fitTo: { mode: "width", value: Math.round(width) },
    background,
    logLevel: "error",
  });
  return resvg.render().asPng();
}

/* ── the app-icon source of truth ─────────────────────────────────────────
 * iOS and Android are generated from THIS file, so the store icon, the
 * adaptive icon foreground and the brand-kit icons cannot drift apart.
 */
function appIconSvg({ tile = false, markRatio = 0.68, background = "gradient" } = {}) {
  const fill =
    background === "gradient"
      ? `<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${DEEP}"/><stop offset="100%" stop-color="${NAVY}"/></linearGradient>${gradientDefs("grad")}</defs>` +
        `<rect width="1024" height="1024" fill="url(#bg)"/>`
      : `<defs>${gradientDefs("grad")}</defs><rect width="1024" height="1024" fill="${background}"/>`;
  const m = Math.round(1024 * markRatio);
  const off = Math.round((1024 - m) / 2);
  return svg(
    1024,
    1024,
    fill +
      `<g transform="translate(${off} ${off}) scale(${round((m / 48) * 1000) / 1000})">${markBody({
        fill: "url(#grad)",
        defs: "",
      })}</g>`,
  );
}

function appIconForegroundSvg() {
  // Android adaptive icons: the mark lives inside the 66% safe zone.
  const m = Math.round(1024 * 0.44);
  const off = Math.round((1024 - m) / 2);
  return svg(
    1024,
    1024,
    `<defs>${gradientDefs("grad")}</defs><g transform="translate(${off} ${off}) scale(${round((m / 48) * 1000) / 1000})">${markBody({
      fill: "url(#grad)",
      defs: "",
    })}</g>`,
  );
}

