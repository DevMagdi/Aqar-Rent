#!/usr/bin/env node
/**
 * Aqar Rent — brand kit generator.
 *
 * One command builds the whole `brand/Aqar-Rent-Brand-Kit/` tree from SVG
 * geometry + `design/tokens.json`. Nothing here is hand-drawn twice: the mark
 * exists once (as a string), the wordmarks exist once (as outlines produced by
 * scripts/outline-wordmark.py), and every raster is a render of those vectors.
 *
 * Why a generator instead of a Figma export
 * -----------------------------------------
 * A palette change must be a one-line edit in design/tokens.json. If the logos
 * were binary exports, the "no invented colours" rule would rot the first time
 * someone needed a PNG at a new size. `--check` re-renders everything and
 * byte-compares it, so CI catches drift in SVG *and* in every PNG.
 *
 * Usage:
 *   node scripts/build-brand-kit.mjs            # write the kit
 *   node scripts/build-brand-kit.mjs --check    # verify, write nothing
 *
 * Requires: @resvg/resvg-js (root devDependency).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "brand", "Aqar-Rent-Brand-Kit");
const TOKENS = JSON.parse(fs.readFileSync(path.join(ROOT, "design/tokens.json"), "utf8"));
const OUTLINES = JSON.parse(fs.readFileSync(path.join(ROOT, "design/wordmark-outlines.json"), "utf8"));

