/* ── main ────────────────────────────────────────────────────────────────── */
function main() {
  const check = process.argv.includes("--check");
  const driftedExternals = [];
  if (!check) {
    fs.rmSync(OUT, { recursive: true, force: true });
    fs.mkdirSync(OUT, { recursive: true });
  }

  // SVGs must exist on disk before their PNGs are rasterised, so build in two
  // passes: write the vector tree, then read it back for rendering.
  buildSvgTree();
  for (const [rel, data] of files) {
    fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true });
    fs.writeFileSync(path.join(OUT, rel), data);
  }
  buildPngTree();
  buildAnimated();
  buildSocial();
  buildIcons();
  buildEmailSignatures();
  buildGuide();

  for (const [rel, data] of externals) {
    const target = path.join(ROOT, rel);
    if (check) {
      if (!fs.existsSync(target) || !fs.readFileSync(target).equals(Buffer.from(data))) driftedExternals.push(rel);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, data);
    }
  }

  const drifted = [];
  for (const [rel, data] of files) {
    const target = path.join(OUT, rel);
    const buf = Buffer.isBuffer(data) ? data : Buffer.from(data);
    if (check) {
      if (!fs.existsSync(target) || !fs.readFileSync(target).equals(buf)) drifted.push(rel);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, buf);
    }
  }

  // Also verify there are no orphan files in the kit tree.
  if (check && fs.existsSync(OUT)) {
    const known = new Set([...files.keys()].map((r) => path.join(OUT, r)));
    const walk = (dir) => {
      for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, e.name);
        if (e.isDirectory()) walk(full);
        else if (!known.has(full)) drifted.push(`${path.relative(OUT, full)} (orphan)`);
      }
    };
    walk(OUT);
  }

  if (driftedExternals.length) {
    if (check) drifted.push(...driftedExternals.map((f) => `${f} (external)`));
    else console.log(`Updated ${driftedExternals.length} external asset(s).`);
  }
  const pngCount = [...files.keys()].filter((f) => f.endsWith(".png")).length;
  if (check) {
    if (drifted.length) {
      console.error("Brand kit out of date (run `npm run brand:build`):");
      for (const d of drifted) console.error(`  · ${d}`);
      process.exit(1);
    }
    console.log(`Brand kit in sync: ${files.size} files (${pngCount} PNG).`);
    return;
  }
  console.log(`Brand kit written: ${files.size} files (${pngCount} PNG) → brand/Aqar-Rent-Brand-Kit/`);
}

main();
