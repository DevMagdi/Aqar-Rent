const D = TOKENS.color.dark;
const GRADIENT = TOKENS.color.brandKit.gradient.value; // [#E3D2A8, #BDA77E, #8F7A52]
const STOPS = TOKENS.color.brandKit.gradientStops.value; // ["0%","50%","100%"]

